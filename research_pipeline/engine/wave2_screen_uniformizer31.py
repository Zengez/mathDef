"""Screen source-scoped uniformizer meaning from Stacks Definition 10.119.8.

Only the independently sourced DVR uniformizer is reviewed, never a general
local-ring uniformizer. Preserve immutable frozen Wave 1, all 488 mathematical
review decisions and all 640 existing dependency links.
"""
from __future__ import annotations
import argparse,hashlib,json
from pathlib import Path
from .core import Workspace,PipelineError,canonical,digest,jsonl,atomic_json
from .revisions import apply_revision
from .stage5_review_gate import atomic_jsonl
from .wave2_apply_links import check_cycles

SOURCE="https://stacks.math.columbia.edu/tag/00P7"
MID="meaning.wave2.foundation.uniformizer-dvr"
FID="form.wave2.foundation.uniformizer-dvr"
TID="term.wave2.foundation30.uniformizer-dvr"
OID="obs.wave2.foundation30.uniformizer-dvr"
TEXT="Let A be a discrete valuation ring with maximal ideal m. An element π∈A is a uniformizer of A if the principal ideal (π) generated by π equals m."
REASON=("Stacks Definition 10.119.8 directly specifies a discrete valuation ring A and an element π generating its maximal ideal. "
        "The defining equality (π)=m is essential. This does not assert that every local ring has a uniformizer, "
        "nor that an arbitrary generator in a non-DVR has any discrete valuation property. "
        "The independently sourced DVR and maximal-ideal meanings are separate prerequisites.")

def run(root):
 w=Workspace(root)
 base=json.loads((w.root/"state/baseline.json").read_text(encoding="utf-8"))
 if base.get("mode")!="second_wave" or any(w.state(s).get("sealed") for s in ("sources","terms","observations","meanings","relations")):
  raise PipelineError("Only unsealed independent Wave 2 can be extended")
 proof=w.root/"state/wave2_foundations_batch_30.json"
 if not proof.exists() or not json.loads(proof.read_text(encoding="utf-8")).get("source_headline_not_falsely_defined"):
  raise PipelineError("Uniformizer source-only intake not verified")
 before={"sources":9,"terms":374,"observations":797,"relations":640}
 if any(len(w.records(s))!=n for s,n in before.items()):
  raise PipelineError("Unexpected prior source or link counts")
 t=w.records("terms").get(TID);obs=w.records("observations").get(OID)
 if not t or not obs or t["locator"]!=SOURCE or obs["locator"]!=SOURCE or obs["term_id"]!=TID or obs["record_kind"]!="paraphrase" or obs["human_verified"] is not False:
  raise PipelineError("Missing direct Stacks 10.119.8 source observation")
 original=w.records("meanings")
 if len(original) not in (476,477):
  raise PipelineError("Unexpected meaning count")
 candidate={
  "id":MID,"term_group_id":"wave2.foundation.uniformizer-dvr",
  "display_term":"uniformizer of a discrete valuation ring",
  "context":"Commutative algebra, Stacks 10.119.8: generator of maximal ideal of discrete valuation ring",
  "term_ids":[TID],"human_verified":False,
  "editorial_status":"source_specific_uniformizer_candidate",
  "formulations":[{"id":FID,"text":TEXT,"evidence_ids":[OID],
                   "review_state":"candidate","human_verified":False}]
 }
 path=w.root/"intake/foundations_batch_31_uniformizer_meaning_candidate.jsonl"
 path.parent.mkdir(parents=True,exist_ok=True)
 payload=canonical(candidate)+"\n"
 if path.exists() and path.read_text(encoding="utf-8")!=payload:
  raise PipelineError("Historical candidate differs")
 path.write_text(payload,encoding="utf-8")
 if len(original)==476:
  w.ingest("meanings",path,batch_size=1)
 else:
  old=original.get(MID)
  if old is None or old["formulations"][0]["text"]!=TEXT:
   raise PipelineError("Previous candidate text differs")
 current=w.records("meanings")[MID]
 form=current["formulations"][0]
 if form["id"]!=FID:raise PipelineError("Formulation identifier changed")
 if form["review_state"]=="candidate":
  revised=dict(current)
  revised["formulations"]=[dict(form,review_state="screened",source_screened_by="assistant_independent_stacks_uniformizer_review_2026_10_19",human_verified=False)]
  revised["editorial_status"]="independently_screened_dvr_uniformizer"
  revised["editorial_screening_reason"]=REASON
  revised["human_verified"]=False
  apply_revision(w.root,{
   "event_id":"revision.wave2.uniformizer31.source_screen01",
   "stage":"meanings","record_id":MID,"before_digest":digest(current),
   "editor":"assistant_independent_stacks_uniformizer_review_2026_10_19",
   "reason":REASON,"operation":"replace","replacement":revised})
 elif form["review_state"]!="screened" or current.get("editorial_screening_reason")!=REASON:
  raise PipelineError("Already reviewed meaning has conflicting mathematical rationale")
 audit=[{"meaning_id":MID,"formulation_id":FID,"source_observation_id":OID,"source_locator":SOURCE,
         "mathematical_reason":REASON,
         "decision":"screen_stacks_dvr_specific_uniformizer_not_arbitrary_local_ring",
         "human_verified":False,"reviewed_by":"assistant_independent_stacks_uniformizer_review_2026_10_19"}]
 evidence=w.root/"wave2/foundation_meaning_review_uniformizer31.jsonl"
 evidence.parent.mkdir(parents=True,exist_ok=True)
 epayload=canonical(audit[0])+"\n"
 if evidence.exists() and evidence.read_text(encoding="utf-8")!=epayload:
  raise PipelineError("Source review event changed")
 evidence.write_text(epayload,encoding="utf-8")
 meanings=w.records("meanings")
 if len(meanings)!=477 or sum(len(m["formulations"]) for m in meanings.values())!=489:
  raise PipelineError("Unexpected screened meaning/formulation count")
 if any(f["review_state"]!="screened" for m in meanings.values() for f in m["formulations"]):
  raise PipelineError("Meaning still a candidate")
 ledger=w.root/"state/wave2_formulation_reviews.jsonl"
 older=jsonl(ledger)
 snap=w.root/"state/wave2_formulation_reviews_snapshot_488_before_uniformizer31.jsonl"
 if len(older)==488:
  if len({r["formulation_id"] for r in older})!=488 or {i for r in older for i in r["relation_ids"]}!=set(w.records("relations")):
   raise PipelineError("Historical 488 review entries or 640 screened links inconsistent")
  old_text=ledger.read_text(encoding="utf-8")
  if snap.exists() and snap.read_text(encoding="utf-8")!=old_text:
   raise PipelineError("Conflicting 488 review snapshot")
  snap.write_text(old_text,encoding="utf-8")
  atomic_json(w.root/"state/wave2_formulation_reviews_snapshot_488_before_uniformizer31.json",{
    "review_count":488,"screened_links":640,
    "sha256":hashlib.sha256(old_text.encode("utf-8")).hexdigest(),
    "human_peer_verified":False})
  cd=digest(list(meanings.values()))
  migrated=[dict(r,meaning_catalog_digest=cd) for r in older]
  migrated.append({"formulation_id":FID,"meaning_id":MID,"meaning_catalog_digest":cd,
   "decision":"needs_review","relation_ids":[],"original_wave1_disposition":None,
   "source":"wave2_individually_sourced_uniformizer",
   "editorial_reason":"DVR-specific uniformizer source screened; exact prerequisite relationships must be individually reviewed.",
   "reviewed_by":None,"human_verified":False})
  atomic_jsonl(ledger,sorted(migrated,key=lambda r:r["formulation_id"]))
 elif len(older)==489:
  if not snap.exists() or any(r["meaning_catalog_digest"]!=digest(list(meanings.values())) for r in older):
   raise PipelineError("Previously migrated review catalog not verified")
 else:
  raise PipelineError("Wrong historical review count")
 prior=jsonl(snap);after=jsonl(ledger)
 by={r["formulation_id"]:r for r in after}
 if len(prior)!=488 or len(after)!=489 or len(by)!=489:
  raise PipelineError("Snapshot or review identity incomplete")
 for p in prior:
  newer=by.get(p["formulation_id"])
  if not newer or any(newer.get(k)!=v for k,v in p.items() if k!="meaning_catalog_digest"):
   raise PipelineError("Older review decision rewritten")
 if {i for r in after for i in r["relation_ids"]}!=set(w.records("relations")):
  raise PipelineError("Prior links not referenced")
 check_cycles(meanings,w.records("relations"))
 if sum(r["decision"]=="needs_review" for r in after)!=1:
  raise PipelineError("Uniformizer must be the only new pending relation review")
 state=w.state("meanings")
 state.update(total=477,record_digest=digest(list(meanings.values())),
     screened_new_formulations=58,stage4_review_complete=False)
 atomic_json(w.root/"state/meanings.json",state)
 report={
   "phase":"independent_DVR_uniformizer_meaning_screened",
   "meaning_count":477,"reviewed_formulations":489,"new_meanings_screened":1,
   "historical_formulations_preserved":488,"screened_links_preserved":640,
   "uniformizer_specific_to_DVR":True,"principal_generator_equality_required":True,
   "new_formulations_awaiting_link_review":1,
   "all_wave2_stages_unsealed":True,"human_peer_verified":False,
   "original_production_mathdef_consulted":False,
   "next":"Individually screen links to DVR valuation context, commutative maximal ideal and two-sided ideal, without equating DVR and arbitrary local rings."
 }
 atomic_json(w.root/"state/wave2_uniformizer31_meaning_screen.json",report)
 return report

def main():
 ap=argparse.ArgumentParser(description=__doc__)
 ap.add_argument("--workspace",type=Path,required=True)
 args=ap.parse_args()
 print(json.dumps(run(args.workspace),indent=2))
if __name__=="__main__":main()
