"""Four independently read ProofWiki alternatives to policy-blocked PlanetMath titles.

Do not read blocked PlanetMath URLs, attribute their content to ProofWiki, or
automatically approve meaning variants or dependencies. Strictly source-logged.
"""
from __future__ import annotations
import argparse,json
from pathlib import Path
from .core import Workspace,PipelineError,canonical,jsonl,atomic_json

DEFS=[
 dict(key="borelsigmaalgebra",name="Borel sigma-algebra of a topological space",
      url="https://proofwiki.org/wiki/Definition%3ABorel_Sigma-Algebra",
      text="For a topological space (X,τ), the Borel sigma-algebra is the smallest sigma-algebra on X containing all open subsets of X. Its elements are the Borel subsets of X.",
      context="Topological Borel sigma-algebra generated by the topology, not an arbitrary sigma-algebra",
      note="The Borel sigma-algebra requires the minimal sigma-algebra containing τ. The restricted Euclidean metric convention is a specific context, not a general defining restriction."),
 dict(key="adjacencymatrix",name="adjacency matrix (simple undirected graph)",
      url="https://proofwiki.org/wiki/Definition%3AAdjacency_Matrix",
      text="Given a finite simple undirected graph G with ordered vertices v_1,…,v_n, its adjacency matrix A has a_ij=1 if the distinct vertices v_i and v_j are joined by an edge and a_ij=0 otherwise.",
      context="Finite simple undirected graph; the matrix depends on vertex ordering and is symmetric with zero diagonal",
      note="Do not automatically identify the binary simple-graph matrix with a weighted adjacency matrix, directed graph matrix or edge-multiplicity matrix. Loops also require a separate convention."),
 dict(key="bipartitegraph",name="bipartite undirected graph",
      url="https://proofwiki.org/wiki/Definition%3ABipartite_Graph",
      text="An undirected graph G=(V,E) is bipartite if there exist disjoint subsets A,B⊆V with A∪B=V and each edge has one endpoint in A and one endpoint in B.",
      context="Bipartite simple undirected graph with possible empty partite sets; not necessarily complete bipartite",
      note="Do not require all possible cross edges: that is the separate notion of a complete bipartite graph. A named partition can be retained as extra structure."),
 dict(key="booleanring",name="Boolean ring under unital and nonunital conventions",
      url="https://proofwiki.org/wiki/Definition%3ABoolean_Ring",
      text="A Boolean ring is a ring whose elements are idempotent: x²=x for every x. In the ProofWiki primary usage the ring has a multiplicative identity; a separate usage does not impose an identity.",
      context="Ring-theory Boolean idempotence; unity requirement differs by context",
      note="The same identity x²=x occurs with and without the unity axiom in sources. Preserve distinct contexts; do not identify Boolean algebras as the exact same type of object.")
]

def run(root):
 w=Workspace(root)
 b=json.loads((w.root/"state/baseline.json").read_text(encoding="utf-8"))
 if b.get("mode")!="second_wave" or any(w.state(s).get("sealed") for s in
     ("sources","terms","observations","meanings","relations")):
  raise PipelineError("Only unsealed independent Wave 2 may ingest source evidence")
 before={"sources":9,"terms":377,"observations":800,"meanings":480,"relations":650}
 after={"sources":9,"terms":381,"observations":804,"meanings":480,"relations":650}
 curr={stage:len(w.records(stage)) for stage in before}
 if curr not in (before,after):
  raise PipelineError("Unexpected baseline for independent source alternatives "+str(curr))
 prior=w.root/"wave2/blocked_planetmath_direct_independent_alternative_sources_batch01_2026-10-20.jsonl"
 if not prior.exists():raise PipelineError("Individual previously policy-blocked source alternatives not audited")
 approved=jsonl(prior)
 if len(approved)!=4 or {a["research_id"].split(".")[-1] for a in approved}!={a["key"] for a in DEFS}:
  raise PipelineError("Four exact original blocked-source alternative audits required")
 source=w.records("sources").get("src.proofwiki")
 if not source or source["access"]!="free" or source["rights"] not in ("permitted","locator_only"):
  raise PipelineError("Independent source access/rights missing")
 ts=[];os=[];leads=[]
 for d in DEFS:
  row=next(x for x in approved if x["research_id"].endswith("."+d["key"]))
  if row["independent_source_locator"]!=d["url"] or row["original_source_access_outcome"]!="policy_blocked_content_not_read":
   raise PipelineError("Original inaccessible source falsely reattributed "+d["key"])
  termid="term.wave2.foundation39."+d["key"];obsid="obs.wave2.foundation39."+d["key"]
  ts.append({"id":termid,"label":d["name"],"source_id":"src.proofwiki",
      "locator":d["url"],
      "discovery_provenance":"independent_ProofWiki_alternative_to_inaccessible_source_2026_10_20",
      "human_verified":False})
  os.append({"id":obsid,"term_id":termid,"source_id":"src.proofwiki",
      "locator":d["url"],"record_kind":"paraphrase","text":d["text"],
      "context":d["context"],"editorial_note":d["note"],
      "original_planetmath_page_content_not_read":True,
      "source_alternative_priority_task_id":row["original_priority_task_id"],
      "reviewed_by":"assistant_independent_proofwiki_source_review_2026_10_20",
      "human_verified":False})
  leads.append({"term_id":termid,"source_id":"src.proofwiki","locator":d["url"],
      "source_access_outcome":"direct_page_read","candidate_observation_id":obsid,
      "source_research_complete":True,"meaning_screened":False,
      "original_blocked_planetmath_locator":row["original_blocked_source_locator"],
      "blocked_original_source_not_verified":True,
      "editorial_reason":d["note"],"human_verified":False})
 def store(path,records):
  path.parent.mkdir(parents=True,exist_ok=True)
  data="".join(canonical(x)+"\n" for x in records)
  if path.exists() and path.read_text(encoding="utf-8")!=data:
   raise PipelineError("Prior source-specific evidence batch changed")
  path.write_text(data,encoding="utf-8")
  return path
 t=w.ingest("terms",store(w.root/"intake/foundations_batch_39_terms.jsonl",ts),batch_size=4)
 o=w.ingest("observations",store(w.root/"intake/foundations_batch_39_observations.jsonl",os),batch_size=4)
 store(w.root/"wave2/foundation_source_discovery_batch_39.jsonl",leads)
 count={stage:len(w.records(stage)) for stage in after}
 if count!=after:raise PipelineError("Independent four-source intake incomplete "+str(count))
 report={"phase":"four_independent_ProofWiki_alternatives_to_policy_blocked_pages_acquired",
  "original_planetmath_pages_remain_unverified":27,
  "independent_alternate_source_terms":4,"independent_alternate_source_observations":4,
  "source_terms_total":381,"source_observations_total":804,
  "screened_meanings_unchanged":480,"screened_links_unchanged":650,
  "new_meanings_screened":0,"new_links_screened":0,
  "borel_requires_topology_generation":True,
  "boolean_ring_unity_variants_preserved":True,
  "simple_adjacency_not_equated_to_weighted_or_multigraph":True,
  "bipartite_not_identified_with_complete_bipartite":True,
  "idempotent_term_skips":t["already_present"],"idempotent_observation_skips":o["already_present"],
  "all_stages_unsealed":True,"human_peer_verified":False,
  "original_production_mathdef_consulted":False,
  "next":"Archive 377-term source ledger, then individually screen context-specific Borel graph and Boolean ring meanings and their prerequisite links."}
 atomic_json(w.root/"state/wave2_foundations_batch_39.json",report)
 return report

def main():
 ap=argparse.ArgumentParser(description=__doc__)
 ap.add_argument("--workspace",type=Path,required=True)
 a=ap.parse_args()
 print(json.dumps(run(a.workspace),indent=2))
if __name__=="__main__":main()
